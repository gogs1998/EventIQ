import type { Fighter } from "@/lib/types";

/**
 * What the sequence has to show where a fighter's face should be.
 *
 * Three states, in order of preference, and the order is the whole point of this
 * file. A cutout parallaxes against the backdrop and is what the sequence was
 * designed around. A photograph does not, but it is the fighter's actual face,
 * and a fighter who sent one and got an initialled plate anyway is the worst
 * outcome of the three: they did the thing they were asked to do and the video
 * says they ignored us. The plate is for the fighter who genuinely sent nothing,
 * which on an amateur card is most of the bill and is a state rather than a
 * fault.
 *
 * Cutouts are generated by the renderer rather than at upload — see
 * scripts/cutouts.mjs — so "photograph, no cutout yet" is the normal condition
 * of a fighter between submitting their form and the next render. It has to look
 * deliberate, not like a missing asset.
 */
export type Portrait =
  /**
   * Poster art the fighter asked for and then approved. First, and only ever
   * reachable through a stored column that nothing but an approval writes.
   */
  | { kind: "stylised"; src: string }
  /** Background removed. Moves independently of the backdrop. */
  | { kind: "cutout"; src: string }
  /** The photograph as sent. Soft-masked and moved less, because it is a plane. */
  | { kind: "photo"; src: string }
  /** Nothing sent. The initialled plate. */
  | { kind: "plate" };

/**
 * The stylised portrait goes above the cutout, and the reason is consent rather
 * than picture quality.
 *
 * A cutout is something we made from a fighter's photograph without asking. A
 * stylised portrait is something they opted into, waited for, looked at and
 * pressed approve on, and it is the only one of the four that answers a question
 * they were actually asked. Ranking it below the cutout would mean the fighter
 * approving an image and then not seeing it, which is worse than any of the
 * treatments looking better than another.
 *
 * It cannot displace a real photograph by accident, because it is null until an
 * approval writes it and it is cleared whenever the photograph it was made from
 * is replaced — the same rule the cutout is held to. Generated art is never what
 * a fighter gets for sending a picture and saying nothing.
 */
export function portraitOf(
  fighter: Pick<Fighter, "cutout" | "photo" | "stylised" | "cutoutQuality" | "tidied">,
): Portrait {
  if (fighter.stylised) return { kind: "stylised", src: fighter.stylised };
  if (cutoutUsable(fighter)) return { kind: "cutout", src: fighter.cutout! };
  // A tidied copy the fighter approved stands in for the photograph it was made
  // from, and is what the renderer cuts out while it is set (cutoutSourceOf). It
  // is still a photograph of them, so it moves like one.
  if (fighter.tidied) return { kind: "photo", src: fighter.tidied };
  if (fighter.photo) return { kind: "photo", src: fighter.photo };
  return { kind: "plate" };
}

/**
 * Whether there is a cutout and the renderer thought it worth showing.
 *
 * A "poor" cutout — a subject too small to read, a head through the top of the
 * frame, two people the mask could not separate (scripts/photo-quality.mjs) — is
 * kept on the row and never shown. What is shown instead is the photograph,
 * which is the fighter's own face in a rectangle and is never worse than a
 * cutout that is wrong; the plate only where there is no photograph at all,
 * which cannot be the case here because a cutout is only ever made from one.
 *
 * No verdict is not a poor one. The curated cutouts and anything cut before the
 * renderer judged its work have none, and they were all shown before this
 * existed: silence is not evidence, in either direction.
 */
export function cutoutUsable(fighter: Pick<Fighter, "cutout" | "cutoutQuality">): boolean {
  return !!fighter.cutout && fighter.cutoutQuality !== "poor";
}

/**
 * Everything derived from one particular photograph, as it is set when that
 * photograph is replaced.
 *
 * One list, because the upload, the poster crop and the questionnaire's save all
 * replace a photograph and each of them used to name the columns it cleared:
 * a derived column added later and forgotten in one of them is a verdict, a
 * cutout or a drawing of somebody's previous picture left on their card.
 */
export const CLEARED_WITH_PHOTO = {
  cutout: null,
  cutoutQuality: null,
  cutoutIssues: null,
  stylised: null,
  tidied: null,
} as const;

/**
 * Whether what is shown is the tidied copy, or a cutout of it. Either way it
 * is an edited photograph and is labelled as one.
 */
export function portraitIsTidied(fighter: Pick<Fighter, "tidied">, portrait: Portrait): boolean {
  return !!fighter.tidied && (portrait.kind === "photo" || portrait.kind === "cutout");
}

/**
 * How far the subject travels against the backdrop, as a fraction of the full
 * cutout move.
 *
 * A cut-out subject can slide a long way over a drifting backdrop and read as
 * depth, because its edge is the fighter's own silhouette. A rectangle cannot:
 * the further it travels the more plainly it is a photograph being dragged
 * across a picture, and past a certain speed the eye stops seeing a fighter and
 * starts seeing a slide transition. So the photograph moves, because a still
 * frame in a moving sequence looks broken, but it moves about a third as far and
 * pushes in half as much.
 */
export const PARALLAX_TRAVEL: Record<Portrait["kind"], number> = {
  cutout: 1,
  photo: 0.34,
  // Poster art comes back as a rectangle with a background of its own, so it is
  // a plane in the frame exactly as a photograph is and travels the same way.
  stylised: 0.34,
  plate: 1,
};

export function parallaxTravel(portrait: Portrait): number {
  return PARALLAX_TRAVEL[portrait.kind];
}

/**
 * Whether a cutout already on the profile is still a cutout of the photograph
 * that is on it.
 *
 * A cutout is derived from one particular photograph. Replace the photograph and
 * the stored cutout is a picture of something that is no longer on the card —
 * a previous haircut, a previous gym vest, or on a returning fighter a previous
 * person entirely if the promoter reassigned the row. So it is discarded and the
 * renderer cuts the new one out. Until it does, the video shows the photograph,
 * which is the fighter as they are now.
 */
export function cutoutSurvives(
  previousPhoto: string | null | undefined,
  nextPhoto: string | null | undefined,
): boolean {
  return (previousPhoto ?? null) === (nextPhoto ?? null);
}

/**
 * The bucket key behind a stored portrait path, or null for anything else.
 *
 * Only `/media/...` is ours to delete. The seeded card's photographs are static
 * assets committed under public/, and an absolute URL or a blob: from a preview
 * is not an object at all, so both come back null and nothing is deleted for
 * them. The same character rule as parseMediaKey, so a path this accepts is a
 * path that route would have served.
 */
export function mediaKeyOf(path: string | null | undefined): string | null {
  if (!path || !path.startsWith("/media/")) return null;
  const key = path.slice("/media/".length);
  if (!/^[A-Za-z0-9][A-Za-z0-9._/-]*$/.test(key) || key.includes("..")) return null;
  return key;
}

/** Where a stylised portrait lives. Its own prefix, so /media can have a rule for it. */
export const STYLISED_PREFIX = "portraits";

/** Where a tidied photograph lives. Its own prefix, so it is never mistaken for an upload. */
export const TIDIED_PREFIX = "tidied";

/**
 * The photograph the renderer cuts out: the tidied copy where the fighter
 * approved one, and the photograph they sent otherwise. One answer, read by
 * scripts/cutouts.mjs, so the cutout and the card agree on which picture is the
 * fighter's.
 */
export function cutoutSourceOf(fighter: {
  photo?: string | null;
  tidied?: string | null;
}): string | null {
  return fighter.tidied || fighter.photo || null;
}

/**
 * The prefixes of the objects that are pictures of one fighter: the photograph
 * they sent (or the promoter cropped), the renderer's cutout of it, the
 * stylised portrait and the tidied copy. Every one is written as `<prefix>/<fighterId>-<suffix>.<ext>`.
 */
export const FIGHTER_MEDIA_PREFIXES = ["fighters", "cutouts", STYLISED_PREFIX, TIDIED_PREFIX] as const;

/**
 * The bucket key behind a path, but only where the key is one of this fighter's
 * own pictures — or null.
 *
 * Every action that deletes a "superseded" picture deletes whatever path the
 * fighter's row holds, and a path on a row is only as trustworthy as whatever
 * last wrote it. A key that names another fighter, a show's render or a
 * sponsor's emblem is never this fighter's to remove, so nothing is deleted for
 * it however it got there (HANDOVER bug 51). Fighter ids are hyphenated, so the
 * id is matched as a prefix and the remainder has to be a bare suffix and
 * extension with no hyphen in it, or `owen-pryce` would own `owen-pryce-2`'s.
 */
export function ownMediaKeyOf(path: string | null | undefined, fighterId: string): string | null {
  const key = mediaKeyOf(path);
  if (!key || !fighterId) return null;
  const slash = key.indexOf("/");
  if (slash < 0) return null;
  if (!(FIGHTER_MEDIA_PREFIXES as readonly string[]).includes(key.slice(0, slash))) return null;
  const name = key.slice(slash + 1);
  if (!name.startsWith(`${fighterId}-`)) return null;
  return /^[A-Za-z0-9]{4,32}\.[a-z]{3,4}$/.test(name.slice(fighterId.length + 1)) ? key : null;
}

/**
 * The photograph a save from the questionnaire may leave on the row.
 *
 * The draft carries the photo path back from the browser, so it is a claim and
 * not a fact: believed, it let anybody holding an invite point their row at any
 * object in the bucket — another fighter's draft photograph, which `/media` then
 * served because it hung off a published card, or a key the next upload would
 * delete as "superseded" (HANDOVER bug 51). The only photograph that ever
 * reaches the row is one an upload put there, so a save keeps the stored one or
 * clears it, and never names a different one. A path that differs is a stale
 * save landing after an upload, and is ignored rather than obeyed.
 */
export function photoToKeep(
  stored: string | null | undefined,
  requested: string | null | undefined,
): string | undefined {
  if (!requested) return undefined;
  return stored ?? undefined;
}

/** The key for one, with the random suffix that stops a replacement being cached. */
export function stylisedKey(fighterId: string, suffix: string, extension: string): string {
  return `${STYLISED_PREFIX}/${fighterId}-${suffix}.${extension}`;
}

/**
 * Whether a path names a stylised portrait of this fighter.
 *
 * The approve action takes the path back from the browser, so it has to be
 * checked rather than believed: without this, a fighter holding one invite could
 * approve any object in the prefix onto their own card, including one drawn from
 * somebody else's photograph. Fighter ids are hyphenated, so the id is matched
 * as a prefix and the remainder has to be the suffix and extension this file
 * writes rather than anything else containing a hyphen.
 */
export function stylisedBelongsTo(path: string, fighterId: string): boolean {
  const key = ownMediaKeyOf(path, fighterId);
  return !!key && key.startsWith(`${STYLISED_PREFIX}/`);
}

/** The key for a tidied photograph, with the random suffix. */
export function tidiedKey(fighterId: string, suffix: string, extension: string): string {
  return `${TIDIED_PREFIX}/${fighterId}-${suffix}.${extension}`;
}

/**
 * Whether a path names a tidied photograph of this fighter. The same check, for
 * the same reason, as `stylisedBelongsTo`: approve takes the path back from the
 * browser.
 */
export function tidiedBelongsTo(path: string, fighterId: string): boolean {
  const key = ownMediaKeyOf(path, fighterId);
  return !!key && key.startsWith(`${TIDIED_PREFIX}/`);
}

/**
 * The initials on the plate. Two words at most, because three initials on a
 * 220px slab reads as an acronym rather than a person.
 */
export function plateInitials(name: string): string {
  return name
    .split(/\s+/)
    .filter(Boolean)
    .slice(0, 2)
    .map((part) => part[0]?.toUpperCase() ?? "")
    .join("");
}
